import { env } from '@/lib/cf';
import JSZip from 'jszip';

export async function generateWipeoutPackage(saasId: string): Promise<ArrayBuffer> {
    const bindings = env();
    const db = bindings?.DRACO_DB;
    if (!db) throw new Error("Database connection failed");

    // 1. Fetch SaaS Metadata
    const saasResult = await db.prepare("SELECT * FROM saas_instances WHERE id = ?").bind(saasId).first<any>();
    if (!saasResult) throw new Error("SaaS Instance not found");

    // 2. Fetch Strategic Dossier (Client Level)
    // We assume the dossier is per tenant, but we want the one relevant to this SaaS.
    // We can try to find the latest "active" or "analyzed" dossier for this tenant.
    const dossierResult = await db.prepare(`
    SELECT * FROM tenant_strategic_dossiers 
    WHERE tenant_id = ? 
    ORDER BY created_at DESC 
    LIMIT 1
  `).bind(saasResult.tenant_id).first<any>();

    // 3. Fetch SaaS Blueprint (SaaS Level)
    const blueprintResult = await db.prepare(`
    SELECT * FROM saas_blueprints 
    WHERE saas_id = ?
  `).bind(saasId).first<any>();

    // 4. Fetch Work Logs (Execution History)
    const logsResult = await db.prepare(`
    SELECT * FROM agent_work_logs 
    WHERE saas_id = ? 
    ORDER BY created_at DESC
  `).bind(saasId).all<any>();
    const logs = logsResult.results || [];

    // 5. Fetch Financial History (Metrics)
    // We can use metrics table if populated, or derive from logs. 
    // For now let's dump the raw logs.

    // 6. Build ZIP
    const zip = new JSZip();
    const root = zip.folder(`drako-export-${saasResult.slug}`);

    // README
    root?.file("README.md", `# ${saasResult.name} - Asset Export
  
Generated by Drako Engine on ${new Date().toISOString()}.

## Contents
- **strategy/**: Your strategic dossier (Market Analysis, SWOT, Plan).
- **architecture/**: The technical blueprint used to build this SaaS.
- **execution/**: Full log of automated tasks performed by Drako Agents.
- **assets/**: Raw JSON data of your instance.

## Ownership
This export confirms your full ownership of the data and strategy contained herein.
  `);

    // Strategy
    if (dossierResult) {
        const strat = root?.folder("strategy");
        strat?.file("dossier.json", JSON.stringify(dossierResult, null, 2));

        // Attempt to extract nice readable parts
        try {
            const formData = JSON.parse(dossierResult.form_data || "{}");
            const analysisData = JSON.parse(dossierResult.analysis_data || "{}");
            const planData = JSON.parse(dossierResult.plan_data || "{}");

            strat?.file("business_profile.json", JSON.stringify(formData, null, 2));
            strat?.file("market_analysis.json", JSON.stringify(analysisData, null, 2));
            strat?.file("strategic_plan.json", JSON.stringify(planData, null, 2));
        } catch (e) { }
    }

    // Architecture
    if (blueprintResult) {
        const arch = root?.folder("architecture");
        arch?.file("blueprint.json", JSON.stringify(blueprintResult, null, 2));
    }

    // Execution
    if (logs.length > 0) {
        const exec = root?.folder("execution");
        // CSV Header
        let csv = "id,created_at,agent,action,status,cost_eur,output_snippet\n";
        logs.forEach(log => {
            const outputSnippet = (log.output_json || "").substring(0, 100).replace(/[\n,]/g, ' ');
            csv += `${log.id},${log.created_at},${log.agent_name},${log.action_type},${log.status},${log.cost_eur || 0},"${outputSnippet}"\n`;
        });
        exec?.file("work_logs.csv", csv);
        exec?.file("work_logs_full.json", JSON.stringify(logs, null, 2));
    }

    // Metadata
    root?.file("assets/saas_metadata.json", JSON.stringify(saasResult, null, 2));

    return await zip.generateAsync({ type: "arraybuffer" });
}
