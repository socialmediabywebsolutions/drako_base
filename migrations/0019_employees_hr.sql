--- Employee roles catalogue
CREATE TABLE IF NOT EXISTS employee_roles (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL,
  saas_id TEXT NOT NULL,
  slug TEXT NOT NULL,
  label TEXT NOT NULL,
  description TEXT,
  permissions TEXT,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
CREATE INDEX IF NOT EXISTS idx_employee_roles_tenant_saas ON employee_roles(tenant_id, saas_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_employee_roles_slug ON employee_roles(tenant_id, saas_id, slug);

-- Employee contracts capture compensation basis and legal metadata
CREATE TABLE IF NOT EXISTS employee_contracts (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL,
  saas_id TEXT NOT NULL,
  employee_id TEXT NOT NULL,
  contract_type TEXT NOT NULL,
  base_salary_monthly REAL,
  hourly_rate REAL,
  commission_percent REAL,
  max_hours_week REAL,
  min_hours_week REAL,
  start_date TEXT NOT NULL,
  end_date TEXT,
  is_active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
CREATE INDEX IF NOT EXISTS idx_employee_contracts_tenant_saas ON employee_contracts(tenant_id, saas_id);
CREATE INDEX IF NOT EXISTS idx_employee_contracts_employee ON employee_contracts(employee_id);

-- Weekly schedules per employee
CREATE TABLE IF NOT EXISTS employee_schedules (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL,
  saas_id TEXT NOT NULL,
  employee_id TEXT NOT NULL,
  day_of_week INTEGER NOT NULL,
  start_time TEXT NOT NULL,
  end_time TEXT NOT NULL,
  break_minutes INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
CREATE INDEX IF NOT EXISTS idx_employee_schedules_tenant_saas ON employee_schedules(tenant_id, saas_id);
CREATE INDEX IF NOT EXISTS idx_employee_schedules_employee ON employee_schedules(employee_id, day_of_week);

-- HR flags generated by Fairness Guard
CREATE TABLE IF NOT EXISTS employee_hr_flags (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL,
  saas_id TEXT NOT NULL,
  employee_id TEXT NOT NULL,
  is_underpaid_suspected INTEGER NOT NULL DEFAULT 0,
  is_overworked_suspected INTEGER NOT NULL DEFAULT 0,
  is_low_performance_suspected INTEGER NOT NULL DEFAULT 0,
  last_review_at TEXT,
  notes TEXT,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
CREATE INDEX IF NOT EXISTS idx_employee_hr_flags_tenant_saas ON employee_hr_flags(tenant_id, saas_id);
CREATE INDEX IF NOT EXISTS idx_employee_hr_flags_employee ON employee_hr_flags(employee_id);

-- HR settings configurable per SaaS (min wage, weekly hours, activity thresholds)
CREATE TABLE IF NOT EXISTS employee_hr_settings (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL,
  saas_id TEXT NOT NULL,
  min_hourly_wage REAL,
  max_weekly_hours REAL,
  low_activity_appointments INTEGER,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_employee_hr_settings_tenant_saas ON employee_hr_settings(tenant_id, saas_id);

-- Historical timesheets per employee per day (optional downstream features)
CREATE TABLE IF NOT EXISTS employee_timesheets (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL,
  saas_id TEXT NOT NULL,
  employee_id TEXT NOT NULL,
  date TEXT NOT NULL,
  scheduled_minutes INTEGER NOT NULL DEFAULT 0,
  worked_minutes INTEGER NOT NULL DEFAULT 0,
  extra_minutes INTEGER NOT NULL DEFAULT 0,
  late_minutes INTEGER NOT NULL DEFAULT 0,
  break_minutes INTEGER NOT NULL DEFAULT 0,
  source TEXT NOT NULL DEFAULT 'MANUAL',
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
CREATE INDEX IF NOT EXISTS idx_employee_timesheets_tenant ON employee_timesheets(tenant_id, saas_id);
CREATE INDEX IF NOT EXISTS idx_employee_timesheets_employee ON employee_timesheets(employee_id, date);

-- Payroll runs summarize payments per employee per period
CREATE TABLE IF NOT EXISTS employee_payroll_runs (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL,
  saas_id TEXT NOT NULL,
  employee_id TEXT NOT NULL,
  period_start TEXT NOT NULL,
  period_end TEXT NOT NULL,
  base_gross_amount REAL NOT NULL DEFAULT 0,
  overtime_amount REAL NOT NULL DEFAULT 0,
  commission_amount REAL NOT NULL DEFAULT 0,
  other_adjustments REAL NOT NULL DEFAULT 0,
  total_gross_amount REAL NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'DRAFT',
  notes TEXT,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
CREATE INDEX IF NOT EXISTS idx_employee_payroll_runs_tenant ON employee_payroll_runs(tenant_id, saas_id);
CREATE INDEX IF NOT EXISTS idx_employee_payroll_runs_employee ON employee_payroll_runs(employee_id, period_start, period_end);

-- HR events capture compliance / performance logs
CREATE TABLE IF NOT EXISTS employee_hr_events (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL,
  saas_id TEXT NOT NULL,
  employee_id TEXT NOT NULL,
  event_type TEXT NOT NULL,
  severity TEXT NOT NULL,
  message TEXT NOT NULL,
  created_by TEXT NOT NULL DEFAULT 'SYSTEM',
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
CREATE INDEX IF NOT EXISTS idx_employee_hr_events_tenant ON employee_hr_events(tenant_id, saas_id);
CREATE INDEX IF NOT EXISTS idx_employee_hr_events_employee ON employee_hr_events(employee_id, created_at);
